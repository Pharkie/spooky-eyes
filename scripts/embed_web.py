"""Compile the web pages into the firmware.

Gzips every file in web/ and writes src/generated/web_assets.h: an array of {path, content type,
ETag, gzipped bytes, length} that src/web/web_server.cpp serves with "Content-Encoding: gzip".
There's no filesystem partition, so an OTA firmware update updates the pages too.

Runs automatically before each `pio run` (extra_scripts = pre:scripts/embed_web.py), or by hand:

    python3 scripts/embed_web.py

The header is only rewritten when its contents change, so builds stay incremental.

The build stops if web/ or one of the pages is missing, or if web/ holds a file of a type the pumpkin
can't serve properly. Editor leftovers (name~, .bak, .swp, dot-files such as .DS_Store) are skipped.
"""

import gzip
import hashlib
import os
import sys
from pathlib import Path

CONTENT_TYPES = {
    ".html": "text/html; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".js": "application/javascript; charset=utf-8",
    ".json": "application/json",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".ico": "image/x-icon",
    ".txt": "text/plain; charset=utf-8",
    ".webmanifest": "application/manifest+json",
    ".woff2": "font/woff2",
}

# The pages web_server.cpp serves by name: without them the pumpkin would be useless
REQUIRED_FILES = ("index.html", "setup.html", "settings.html")

# Editor backups and swap files: never shipped
JUNK_SUFFIXES = ("~", ".bak", ".swp", ".swo", ".tmp", ".orig")

BYTES_PER_LINE = 20
SCRIPT_VERSION = "2"  # bump when the header layout changes, so old headers get rewritten

# Under PlatformIO this runs inside SCons, which provides Import(); standalone there's no env
try:
    Import("env")  # noqa: F821
except NameError:
    env = None


def project_dir():
    # SCons doesn't set __file__, but its env knows the project folder
    if env is not None:
        return Path(env.subst("$PROJECT_DIR"))
    return Path(os.path.abspath(sys.argv[0])).resolve().parent.parent


def fail(message):
    """Stop the build (or the script) with a message saying what to fix."""
    print(f"embed_web: ERROR: {message}", file=sys.stderr)
    if env is not None:
        env.Exit(1)
    sys.exit(1)


def c_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def is_junk(relative):
    return any(part.startswith(".") for part in relative.parts) or relative.name.endswith(JUNK_SUFFIXES)


def web_files(web_dir):
    """Every file in web/ to embed, after checking the pages are there and every type is known."""
    if not web_dir.is_dir():
        fail(f"{web_dir} is missing: the pumpkin's pages live there")
    files = []
    unknown = []
    for path in sorted(web_dir.rglob("*")):
        relative = path.relative_to(web_dir)
        if not path.is_file() or is_junk(relative):
            continue
        if path.suffix.lower() not in CONTENT_TYPES:
            unknown.append(relative.as_posix())
            continue
        files.append(path)
    if unknown:
        fail("don't know how to serve " + ", ".join(unknown) +
             ": add its type to CONTENT_TYPES in scripts/embed_web.py, or move it out of web/")
    missing = [name for name in REQUIRED_FILES if not (web_dir / name).is_file()]
    if missing:
        fail("web/ is missing " + ", ".join(missing))
    return files


def pack(raw):
    # mtime=0, and the "made on" OS byte fixed, so every Python makes the same bytes for the same file
    packed = bytearray(gzip.compress(raw, compresslevel=9, mtime=0))
    packed[9] = 0xFF
    return bytes(packed)


def inputs_hash(web_dir, files):
    """Changes whenever any file in web/ changes (or SCRIPT_VERSION does)."""
    digest = hashlib.sha1(SCRIPT_VERSION.encode())
    for path in files:
        digest.update(path.relative_to(web_dir).as_posix().encode() + b"\0")
        digest.update(path.read_bytes())
    return digest.hexdigest()


def build_header(web_dir, files, stamp):
    lines = [
        "#pragma once",
        "// Generated by scripts/embed_web.py from web/. Don't edit: change the files in web/ instead.",
        f"// Inputs: {stamp}",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace web_assets",
        "{",
        "    struct Asset",
        "    {",
        "        const char *path;        // e.g. \"/index.html\"",
        "        const char *contentType; // e.g. \"text/html; charset=utf-8\"",
        "        const char *etag;        // changes whenever the file does",
        "        const uint8_t *data;     // gzipped",
        "        size_t length;",
        "    };",
        "",
    ]
    entries = []
    total_raw = 0
    total_gz = 0
    for index, path in enumerate(files):
        raw = path.read_bytes()
        packed = pack(raw)
        total_raw += len(raw)
        total_gz += len(packed)
        url = "/" + path.relative_to(web_dir).as_posix()
        content_type = CONTENT_TYPES[path.suffix.lower()]
        etag = '"' + hashlib.sha1(raw).hexdigest()[:16] + '"'
        name = f"kData{index}"
        lines.append(f"    // {url}: {len(raw)} bytes, {len(packed)} gzipped")
        lines.append(f"    static const uint8_t {name}[] = {{")
        for start in range(0, len(packed), BYTES_PER_LINE):
            chunk = packed[start:start + BYTES_PER_LINE]
            lines.append("        " + ",".join(f"0x{b:02x}" for b in chunk) + ",")
        lines.append("    };")
        lines.append("")
        entries.append(f"        {{{c_string(url)}, {c_string(content_type)}, {c_string(etag)}, {name}, sizeof({name})}},")

    lines.append("    static const Asset kAssets[] = {")
    lines.extend(entries)
    lines.append("    };")
    lines.append("    static constexpr size_t kAssetCount = sizeof(kAssets) / sizeof(kAssets[0]);")
    lines.append("}")
    lines.append("")
    return "\n".join(lines), len(entries), total_raw, total_gz


def main():
    root = project_dir()
    web_dir = root / "web"
    out = root / "src" / "generated" / "web_assets.h"
    files = web_files(web_dir)
    stamp = inputs_hash(web_dir, files)
    # Compare a hash of the inputs, not the output: zlib versions can compress slightly differently
    if out.exists() and f"// Inputs: {stamp}\n" in out.read_text(encoding="utf-8"):
        print(f"embed_web: {len(files)} web files unchanged")
        return
    text, count, total_raw, total_gz = build_header(web_dir, files, stamp)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print(f"embed_web: wrote {out.relative_to(root)} ({count} files, {total_raw} bytes -> {total_gz} gzipped)")


main()
